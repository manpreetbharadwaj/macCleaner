use std::fs;
use std::path::Path;

/// Embeds every UI locale file (../src/i18n/locales/*.json) so the native
/// side — the menu bar and background notifications — speaks the same
/// languages as the UI. Adding a language is just adding a JSON file there.
fn embed_locales() {
    let dir = Path::new("../src/i18n/locales");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut entries: Vec<_> = fs::read_dir(dir)
        .map(|it| it.filter_map(Result::ok).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "json")).collect())
        .unwrap_or_default();
    entries.sort();
    let mut code = String::from("/// (language code, locale JSON) — generated by build.rs.\npub static LOCALES: &[(&str, &str)] = &[\n");
    for path in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
        let lang = path.file_stem().unwrap().to_string_lossy();
        let abs = fs::canonicalize(path).unwrap();
        code.push_str(&format!("    ({lang:?}, include_str!({:?})),\n", abs.display().to_string()));
    }
    code.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("locales.rs");
    fs::write(out, code).unwrap();
}

/// macOS bundle localization, generated from the same locale files:
/// `gen/lproj/<lang>.lproj/InfoPlist.strings` (the localized Finder
/// automation prompt) and `Info.plist`'s CFBundleLocalizations, which also
/// makes the app appear in System Settings → Language & Region → Applications.
fn bundle_localizations() {
    let dir = Path::new("../src/i18n/locales");
    let mut codes: Vec<String> = Vec::new();
    let mut english_usage = String::new();
    let mut paths: Vec<_> = fs::read_dir(dir).map(|it| it.filter_map(Result::ok).map(|e| e.path()).collect()).unwrap_or_default();
    paths.sort();
    let escape = |s: &str| s.replace('\\', "\\\\").replace('"', "\\\"");
    for path in paths.iter().filter(|p| p.extension().is_some_and(|x| x == "json")) {
        let json: serde_json::Value = serde_json::from_str(&fs::read_to_string(path).unwrap()).unwrap();
        // Apple's bundle codes: zh-CN → zh-Hans, zh-TW → zh-Hant.
        let code = match path.file_stem().unwrap().to_string_lossy().as_ref() {
            "zh-CN" => "zh-Hans".to_string(),
            "zh-TW" => "zh-Hant".to_string(),
            other => other.to_string(),
        };
        let usage = json["native"]["appleEventsUsage"].as_str().unwrap_or_default().to_string();
        if code == "en" {
            english_usage = usage.clone();
        }
        let lproj = Path::new("gen/lproj").join(format!("{code}.lproj"));
        fs::create_dir_all(&lproj).unwrap();
        write_if_changed(&lproj.join("InfoPlist.strings"), &format!("\"NSAppleEventsUsageDescription\" = \"{}\";\n", escape(&usage)));
        codes.push(code);
    }
    let localizations: String = codes.iter().map(|c| format!("    <string>{c}</string>\n")).collect();
    let plist = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<!-- Generated by build.rs from src/i18n/locales — edit the locale files instead. -->\n<plist version=\"1.0\">\n<dict>\n  <key>CFBundleDevelopmentRegion</key>\n  <string>en</string>\n  <key>CFBundleLocalizations</key>\n  <array>\n{localizations}  </array>\n  <key>NSAppleEventsUsageDescription</key>\n  <string>{}</string>\n</dict>\n</plist>\n",
        english_usage.replace('&', "&amp;").replace('<', "&lt;")
    );
    write_if_changed(Path::new("Info.plist"), &plist);
}

fn write_if_changed(path: &Path, contents: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(contents) {
        fs::write(path, contents).unwrap();
    }
}

fn main() {
    embed_locales();
    bundle_localizations();
    tauri_build::build()
}
